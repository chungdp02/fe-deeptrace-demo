import os
TEST_BASE = os.environ.get("DEEPTRACE_BASE_URL", "http://127.0.0.1:5173")
from e2e_helpers import row_action, seed_catalog
"""Kiểm thử với server Admin đang chạy: python -X utf8 apps/admin/e2e/dashboard.py."""
import re
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    context = browser.new_context(viewport={"width":1440,"height":1000})
    page = context.new_page()
    errors=[]
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.on('console', lambda message: errors.append(message.text) if message.type == 'error' else None)
    page.goto(TEST_BASE,wait_until='networkidle')
    page.evaluate('localStorage.clear(); localStorage.setItem("deeptrace.admin.preferences.v1", "3")')
    page.reload(wait_until='networkidle')
    expect(page.get_by_role('heading',name='Tổng quan')).to_be_visible()
    page.get_by_role('link',name='Sản phẩm',exact=True).click()
    search=page.get_by_role('searchbox',name='Tìm kiếm sản phẩm')
    search.fill('  ca phe ')
    expect(page.get_by_text('Tìm thấy 1/7 sản phẩm',exact=True)).to_be_visible()
    page.get_by_role('button',name='Đặt lại bộ lọc').click()
    def choose(label,value):
        page.get_by_role('combobox',name=label).click()
        page.get_by_role('option',name=value,exact=True).click()
    choose('Lọc theo trạng thái','Tạm ngưng')
    expect(page.get_by_text('Tìm thấy 3/7 sản phẩm',exact=True)).to_be_visible()
    choose('Sắp xếp sản phẩm','Tên Z–A')
    page.get_by_role('button',name='Đặt lại bộ lọc').click()
    page.get_by_role('button',name='Sau',exact=True).click()
    page.get_by_role('button',name='Sau',exact=True).click()
    expect(page.get_by_text('Trang 3 / 3',exact=True)).to_be_visible()
    page.get_by_role('button',name='Đặt lại bộ lọc').click()
    page.get_by_role('button',name='Thêm sản phẩm',exact=True).click()
    dialog=page.get_by_role('dialog')
    dialog.get_by_role('button',name='Lưu sản phẩm').click()
    assert dialog.get_by_role('alert').count() >= 3
    dialog.get_by_label('Mã sản phẩm').fill('P900')
    dialog.get_by_label('Tên sản phẩm').fill('Sản phẩm kiểm thử')
    dialog.get_by_role('combobox',name='Danh mục sản phẩm').click()
    page.get_by_role('option',name='Nông sản',exact=True).click()
    dialog.get_by_role('button',name='Lưu sản phẩm').click()
    row=page.get_by_role('row').filter(has_text='P900')
    expect(row).to_be_visible()
    row_action(page, row.get_by_role('button').get_attribute('aria-label'), 'Chỉnh sửa')
    dialog=page.get_by_role('dialog')
    dialog.get_by_label('Tên sản phẩm').fill('Không được lưu')
    dialog.get_by_role('button',name='Hủy',exact=True).click()
    expect(row).to_contain_text('Sản phẩm kiểm thử')
    row_action(page, row.get_by_role('button').get_attribute('aria-label'), 'Chỉnh sửa')
    dialog=page.get_by_role('dialog')
    dialog.get_by_label('Tên sản phẩm').fill('Sản phẩm đã cập nhật')
    dialog.get_by_role('button',name='Lưu thay đổi').click()
    expect(row).to_contain_text('Sản phẩm đã cập nhật')
    page.reload(wait_until='networkidle')
    search=page.get_by_role('searchbox',name='Tìm kiếm sản phẩm')
    search.fill('P900')
    row=page.get_by_role('row').filter(has_text='P900')
    expect(row).to_contain_text('Sản phẩm đã cập nhật')
    row_action(page, 'Thao tác sản phẩm P900', 'Xóa sản phẩm')
    alert=page.get_by_role('alertdialog')
    expect(alert).to_be_visible()
    alert.get_by_role('button',name='Hủy',exact=True).click()
    expect(row).to_be_visible()
    row_action(page, 'Thao tác sản phẩm P900', 'Xóa sản phẩm')
    page.get_by_role('alertdialog').get_by_role('button',name='Xác nhận xóa').click()
    expect(page.get_by_text('Tìm thấy 0/7 sản phẩm',exact=True)).to_be_visible()
    search.fill('P001')
    row_action(page, 'Thao tác sản phẩm P001', 'Xóa sản phẩm')
    page.get_by_role('alertdialog').get_by_role('button',name='Xác nhận xóa').click()
    expect(page.get_by_role('alertdialog').get_by_role('alert')).to_contain_text('Không thể xóa sản phẩm')
    page.get_by_role('alertdialog').get_by_role('button',name='Hủy',exact=True).click()
    expect(page.get_by_role('row').filter(has_text='P001')).to_be_visible()
    page.get_by_role('link',name='Tổng quan',exact=True).click()
    expect(page.get_by_text('Tổng sản phẩm',exact=True).locator('xpath=../..')).to_contain_text('7')
    page.go_back()
    expect(page.get_by_role('heading',name='Sản phẩm')).to_be_visible()
    page.go_forward()
    expect(page.get_by_role('heading',name='Tổng quan')).to_be_visible()
    for width in [375,390,768,1024,1440]:
        page.set_viewport_size({"width":width,"height":1000})
        page.goto(TEST_BASE+'/products',wait_until='networkidle')
        page.wait_for_function('document.documentElement.scrollWidth <= innerWidth')
        page.get_by_role('button',name='Thêm sản phẩm',exact=True).click()
        expect(page.get_by_role('dialog')).to_be_visible()
        page.keyboard.press('Escape')
        page.get_by_role('dialog').wait_for(state='hidden')
        if width < 768:
            page.get_by_role('button',name='Mở hoặc đóng menu').click()
            page.get_by_role('link',name='Tổng quan',exact=True).click()
            expect(page.get_by_role('heading',name='Tổng quan')).to_be_visible()
        else:
            page.get_by_role('link',name='Tổng quan',exact=True).click()
        page.wait_for_load_state('networkidle')
        page.wait_for_function('document.documentElement.scrollWidth <= innerWidth')
    page.goto(TEST_BASE+'/unknown',wait_until='networkidle')
    expect(page.get_by_role('heading',name='Không tìm thấy trang')).to_be_visible()
    page.get_by_role('link',name='Về tổng quan').click()
    expect(page.get_by_role('heading',name='Tổng quan')).to_be_visible()
    page.evaluate('localStorage.setItem("deeptrace.admin.products.v1", "broken")')
    page.reload(wait_until='networkidle')
    expect(page.get_by_text('Tổng sản phẩm',exact=True).locator('xpath=../..')).to_contain_text('7')
    page.get_by_role('link',name='Sản phẩm',exact=True).click()
    expect(page.get_by_role('button',name='Khôi phục demo')).to_have_count(0)
    seed_catalog(page, empty=True)
    expect(page.get_by_text('Tìm thấy 0/0 sản phẩm',exact=True)).to_be_visible()
    page.get_by_role('link',name='Tổng quan',exact=True).click()
    expect(page.get_by_text('Tổng sản phẩm',exact=True).locator('xpath=../..')).to_contain_text('0')
    page.get_by_role('link',name='Sản phẩm',exact=True).click()
    seed_catalog(page)
    expect(page.get_by_text('Tìm thấy 7/7 sản phẩm',exact=True)).to_be_visible()
    assert not errors,errors
    print('PASS: Product CRUD/cancel/search/filter/sort/pagination, seeded empty state/recovery, routing/history, 5 viewports; console/page errors=0')
    browser.close()
