import re
import os
TEST_BASE = os.environ.get("DEEPTRACE_BASE_URL", "http://127.0.0.1:5173")
from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={"width":1440,"height":1000})
    errors=[]
    page.on("pageerror",lambda error:errors.append(str(error)))
    def nav(route): page.goto(TEST_BASE+route,wait_until="networkidle")
    def fill(label,value): page.get_by_role("dialog").get_by_label(label,exact=False).fill(value)
    def choose(label,value):
        page.get_by_role("combobox",name=label,exact=True).click()
        page.get_by_role("option",name=value,exact=True).click()
    def save():
        page.get_by_role("dialog").get_by_role("button",name=re.compile(r"^Lưu (thông tin|thay đổi)$")).click()
        expect(page.get_by_role("dialog")).not_to_be_visible()
    nav("/company")
    original=page.get_by_label("Tên doanh nghiệp",exact=True).input_value()
    page.get_by_label("Tên doanh nghiệp",exact=True).fill("Chưa lưu")
    page.get_by_role("button",name="Hủy thay đổi",exact=True).click()
    expect(page.get_by_label("Tên doanh nghiệp",exact=True)).to_have_value(original)
    page.get_by_label("Tên doanh nghiệp",exact=True).fill("Doanh nghiệp vận hành E2E")
    page.get_by_label("Email liên hệ").fill("invalid")
    page.get_by_role("button",name=re.compile(r"^Lưu (thông tin|thay đổi)$")).click()
    expect(page.get_by_role("alert")).to_be_visible()
    page.get_by_label("Email liên hệ").fill("company@example.com")
    page.get_by_role("button",name=re.compile(r"^Lưu (thông tin|thay đổi)$")).click()
    page.reload(wait_until="networkidle")
    expect(page.get_by_label("Tên doanh nghiệp",exact=True)).to_have_value("Doanh nghiệp vận hành E2E")
    nav("/categories")
    page.get_by_role("button",name="Thêm danh mục",exact=True).click()
    page.get_by_role("dialog").get_by_role("button",name="Lưu danh mục",exact=True).click()
    expect(page.get_by_role("dialog").get_by_role("alert")).to_be_visible()
    page.get_by_role("dialog").get_by_label("Tên danh mục",exact=True).fill("Danh mục E2E")
    page.get_by_role("dialog").get_by_role("button",name="Lưu danh mục",exact=True).click()
    expect(page.get_by_role("row").filter(has_text="Danh mục E2E")).to_be_visible()
    catalog=page.evaluate("JSON.parse(localStorage.getItem('deeptrace.admin.catalog.v2'))")
    used=catalog["products"][0]["category"]
    page.get_by_role("button",name="Thao tác danh mục "+used,exact=True).click()
    page.get_by_role("menuitem",name="Xóa danh mục",exact=True).click()
    page.get_by_role("alertdialog").get_by_role("button",name="Xác nhận xóa",exact=True).click()
    expect(page.get_by_role("alertdialog").get_by_role("alert")).to_be_visible()
    page.get_by_role("alertdialog").get_by_role("button",name="Hủy",exact=True).click()
    page.get_by_role("button",name="Thao tác danh mục "+used,exact=True).click()
    page.get_by_role("menuitem",name="Chỉnh sửa",exact=True).click()
    page.get_by_role("dialog").get_by_label("Tên danh mục",exact=True).fill("Danh mục đã đổi E2E")
    page.get_by_role("dialog").get_by_role("button",name="Lưu thay đổi",exact=True).click()
    page.reload(wait_until="networkidle")
    migrated=page.evaluate("JSON.parse(localStorage.getItem('deeptrace.admin.catalog.v2'))")
    old_ids={item["id"] for item in catalog["products"] if item["category"]==used}
    assert all(item["category"]=="Danh mục đã đổi E2E" for item in migrated["products"] if item["id"] in old_ids)
    page.get_by_role("button",name="Thao tác danh mục Danh mục E2E",exact=True).click()
    page.get_by_role("menuitem",name="Xóa danh mục",exact=True).click()
    page.get_by_role("alertdialog").get_by_role("button",name="Xác nhận xóa",exact=True).click()
    expect(page.get_by_role("row").filter(has_text="Danh mục E2E")).to_have_count(0)
    nav("/employees")
    page.get_by_role("button",name="Thêm nhân viên",exact=True).click()
    fill("Mã nhân viên","NV-E2E");fill("Họ tên","Nhân sự vận hành E2E");fill("Email nhân viên","operator@example.com")
    page.get_by_role("dialog").get_by_role("button",name="Lưu nhân viên",exact=True).click()
    expect(page.get_by_role("row").filter(has_text="NV-E2E")).to_be_visible()
    page.get_by_role("button",name="Thao tác nhân viên NV-E2E",exact=True).click();page.get_by_role("menuitem",name="Chỉnh sửa",exact=True).click()
    fill("Họ tên","Tên chưa lưu");page.get_by_role("dialog").get_by_role("button",name="Hủy",exact=True).click()
    expect(page.get_by_role("row").filter(has_text="NV-E2E")).to_contain_text("Nhân sự vận hành E2E")
    page.get_by_role("button",name="Thao tác nhân viên NV-E2E",exact=True).click();page.get_by_role("menuitem",name="Xóa nhân viên",exact=True).click()
    page.get_by_role("alertdialog").get_by_role("button",name="Xác nhận xóa",exact=True).click()
    expect(page.get_by_role("row").filter(has_text="NV-E2E")).to_have_count(0)
    nav("/partners");page.get_by_role("button",name="Thêm đối tác",exact=True).click()
    fill("Tên đối tác","Đơn vị mới E2E");fill("Liên hệ","0900000333");fill("Địa chỉ","Đồng Nai");save()
    expect(page.get_by_role("row").filter(has_text="Đơn vị mới E2E")).to_be_visible()
    nav("/locations");page.get_by_role("button",name="Thêm địa điểm",exact=True).click()
    fill("Tên địa điểm","Kho E2E");choose("Đơn vị quản lý","Đơn vị mới E2E");fill("Địa chỉ","Địa chỉ kho E2E");save()
    row=page.get_by_role("row").filter(has_text="Kho E2E");expect(row).to_contain_text("Đơn vị mới E2E")
    row.get_by_role("button").click();page.get_by_role("menuitem",name="Chỉnh sửa",exact=True).click()
    fill("Địa chỉ","Địa chỉ đã cập nhật");save()
    page.reload(wait_until="networkidle")
    expect(page.get_by_role("row").filter(has_text="Kho E2E")).to_contain_text("Địa chỉ đã cập nhật")
    assert not errors,errors
    print("PASS: Category create/validation/protected delete/rename Product refs/persistence/delete; Company validation/cancel/save/persistence; Employee create/cancel/delete; Partner create; Location create/edit/reference/persistence; errors=0")
    browser.close()
